import 'package:youtube_explode_dart/youtube_explode_dart.dart';

import 'caption_models.dart';

class VideoCaptions {
  const VideoCaptions({
    required this.videoId,
    required this.title,
    required this.language,
    required this.autoGenerated,
    required this.cues,
  });

  final String videoId;
  final String title;
  final String language;
  final bool autoGenerated;
  final List<Cue> cues;
}

class CaptionsUnavailable implements Exception {
  CaptionsUnavailable(this.message);

  final String message;

  @override
  String toString() => message;
}

abstract class CaptionSource {
  /// [urlOrId] is a YouTube URL or an 11-character video id.
  Future<VideoCaptions> fetch(String urlOrId, {String preferredLanguage = 'uk'});
}

class YoutubeCaptionSource implements CaptionSource {
  @override
  Future<VideoCaptions> fetch(String urlOrId, {String preferredLanguage = 'uk'}) async {
    final yt = YoutubeExplode();
    try {
      final VideoId id;
      try {
        id = VideoId(urlOrId.trim());
      } catch (_) {
        throw CaptionsUnavailable('Not a YouTube link: $urlOrId');
      }
      final video = await yt.videos.get(id);
      final manifest = await yt.videos.closedCaptions.getManifest(id);
      if (manifest.tracks.isEmpty) {
        throw CaptionsUnavailable('This video has no subtitles.');
      }
      // Hand-made subtitles in the wanted language beat auto-generated ones.
      final tracks = [...manifest.tracks]..sort((a, b) {
          int rank(ClosedCaptionTrackInfo t) =>
              (t.language.code.startsWith(preferredLanguage) ? 0 : 2) +
              (t.isAutoGenerated ? 1 : 0);
          return rank(a).compareTo(rank(b));
        });
      final track = tracks.first;
      final captions = await yt.videos.closedCaptions.get(track);
      return VideoCaptions(
        videoId: id.value,
        title: video.title,
        language: track.language.code,
        autoGenerated: track.isAutoGenerated,
        cues: [
          for (final c in captions.captions)
            Cue(
              startMs: c.offset.inMilliseconds,
              durationMs: c.duration.inMilliseconds,
              text: c.text,
            )
        ],
      );
    } finally {
      yt.close();
    }
  }
}
