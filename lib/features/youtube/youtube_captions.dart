import 'package:youtube_explode_dart/youtube_explode_dart.dart';

import 'caption_models.dart';

class VideoCaptions {
  const VideoCaptions({
    required this.videoId,
    required this.title,
    required this.language,
    required this.autoGenerated,
    required this.cues,
  });

  final String videoId;
  final String title;
  final String language;
  final bool autoGenerated;
  final List<Cue> cues;
}

class CaptionsUnavailable implements Exception {
  CaptionsUnavailable(this.message);

  final String message;

  @override
  String toString() => message;
}

abstract class CaptionSource {
  /// [urlOrId] is a YouTube URL or an 11-character video id. With a
  /// [language] (`uk`, `pt`, …) only subtitles in that language are used; a
  /// video without them is an error, never a silent substitute. Without one,
  /// the video's own (first) track is taken.
  Future<VideoCaptions> fetch(String urlOrId, {String? language});
}

/// The track to use among [available] `(code, autoGenerated)` pairs: hand-made
/// subtitles beat auto-generated ones; null when [language] is given and
/// there is none in it.
int? chooseCaptionTrack(
  List<(String code, bool auto)> available,
  String? language,
) {
  int? best;
  for (var i = 0; i < available.length; i++) {
    final (code, auto) = available[i];
    if (language != null &&
        !code.toLowerCase().startsWith(language.toLowerCase())) {
      continue;
    }
    if (best == null || (!auto && available[best].$2)) best = i;
  }
  return best;
}

class YoutubeCaptionSource implements CaptionSource {
  @override
  Future<VideoCaptions> fetch(String urlOrId, {String? language}) async {
    final yt = YoutubeExplode();
    try {
      final VideoId id;
      try {
        id = VideoId(urlOrId.trim());
      } catch (_) {
        throw CaptionsUnavailable('Not a YouTube link: $urlOrId');
      }
      final video = await yt.videos.get(id);
      final manifest = await yt.videos.closedCaptions.getManifest(id);
      if (manifest.tracks.isEmpty) {
        throw CaptionsUnavailable('This video has no subtitles.');
      }
      final tracks = manifest.tracks.toList();
      final chosen = chooseCaptionTrack([
        for (final t in tracks) (t.language.code, t.isAutoGenerated),
      ], language);
      if (chosen == null) {
        final codes = {for (final t in tracks) t.language.code}.join(', ');
        throw CaptionsUnavailable(
          'This video has no subtitles in $language '
          '(available: $codes).',
        );
      }
      final track = tracks[chosen];
      final captions = await yt.videos.closedCaptions.get(track);
      return VideoCaptions(
        videoId: id.value,
        title: video.title,
        language: track.language.code,
        autoGenerated: track.isAutoGenerated,
        cues: [
          for (final c in captions.captions)
            Cue(
              startMs: c.offset.inMilliseconds,
              durationMs: c.duration.inMilliseconds,
              text: c.text,
            ),
        ],
      );
    } finally {
      yt.close();
    }
  }
}
