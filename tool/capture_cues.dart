// Dumps the subtitle cues of one YouTube video to JSON.
// dart run tool/capture_cues.dart <videoUrl> <out.json>
import 'dart:convert';
import 'dart:io';

import 'package:youtube_explode_dart/youtube_explode_dart.dart';

Future<void> main(List<String> a) async {
  final yt = YoutubeExplode();
  final video = await yt.videos.get(a[0]);
  final manifest = await yt.videos.closedCaptions.getManifest(video.id);
  final track = manifest.tracks.firstWhere((t) => t.language.code.startsWith('uk'),
      orElse: () => manifest.tracks.first);
  final cc = await yt.videos.closedCaptions.get(track);
  File(a[1]).writeAsStringSync(jsonEncode([
    for (final c in cc.captions)
      {'s': c.offset.inMilliseconds, 'd': c.duration.inMilliseconds, 't': c.text}
  ]));
  print('${video.title}: ${cc.captions.length} cues (${track.language.code}, auto=${track.isAutoGenerated})');
  yt.close();
}
