// Lists the subtitle tracks of a YouTube video as youtube_explode sees them.
// dart run tool/list_tracks.dart <videoUrlOrId>
import 'package:youtube_explode_dart/youtube_explode_dart.dart';

Future<void> main(List<String> a) async {
  final yt = YoutubeExplode();
  final manifest = await yt.videos.closedCaptions.getManifest(VideoId(a[0]));
  for (final t in manifest.tracks) {
    print('${t.language.code}  ${t.language.name}  auto=${t.isAutoGenerated}');
  }
  yt.close();
}
