import 'package:youtube_explode_dart/youtube_explode_dart.dart';

Future<void> main(List<String> args) async {
  final yt = YoutubeExplode();
  try {
    final video = await yt.videos.get(args.first);
    print('${video.title} | ${video.author} | ${video.duration}');
    final manifest = await yt.videos.closedCaptions.getManifest(video.id);
    for (final t in manifest.tracks) {
      print('track: ${t.language.code} ${t.language.name} auto=${t.isAutoGenerated}');
    }
    if (manifest.tracks.isEmpty) return;
    final track = manifest.tracks.first;
    final cc = await yt.videos.closedCaptions.get(track);
    print('captions: ${cc.captions.length}');
    for (final c in cc.captions.take(5)) {
      print('${c.offset} +${c.duration}: ${c.text}');
    }
    print('last: ${cc.captions.last.offset}');
  } finally {
    yt.close();
  }
}
